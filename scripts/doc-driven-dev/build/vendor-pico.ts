#!/usr/bin/env node
// Embeds @picocss/pico (MIT) classless CSS into a TypeScript module so the
// dashboard renderer and the bundled CLI share one inlined stylesheet.
import { promises as fs } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const ROOT = process.cwd();
const OUTPUT = path.join(
  ROOT,
  "src",
  "skills",
  "doc-driven-dev-graph",
  "scripts",
  "lib",
  "pico_classless_css.ts"
);

const require = createRequire(import.meta.url);
const packageJson = require.resolve("@picocss/pico/package.json");
const picoCssPath = path.join(path.dirname(packageJson), "css", "pico.classless.min.css");

async function main(): Promise<void> {
  const css = await fs.readFile(picoCssPath, "utf8");
  if (css.includes("</")) {
    throw new Error("Pico CSS contains a closing tag sequence and cannot be inlined safely");
  }

  const license = await fs.readFile(path.join(path.dirname(packageJson), "LICENSE.md"), "utf8").catch(() => "");
  const copyright = license.split("\n").find((line) => /copyright/i.test(line))?.trim()
    ?? "Copyright (c) Pico CSS contributors";

  const output = [
    "// Generated by build/vendor-pico.ts. Do not edit by hand.",
    `// Pico CSS v2 classless - MIT License - ${copyright}`,
    `export const picoClasslessCss = ${JSON.stringify(css)};`,
    ""
  ].join("\n");

  await fs.writeFile(OUTPUT, output, "utf8");
  console.log(`Vendored ${picoCssPath} -> ${path.relative(ROOT, OUTPUT)} (${css.length} bytes)`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
